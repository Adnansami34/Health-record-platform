"""
Step 5a: Export the cleaned database into data.js, so the app can show it.

Run:  python export_for_app.py
Needs: health_record.db (made by pipeline.py)
Creates: data.js  (patients, conditions, allergies, medicines, visits)

Only cleaned data from the database is exported. Rejected rows never reach the app.
"""
import json
import sqlite3
from datetime import date

DB_FILE = "health_record.db"
OUT_FILE = "data.js"

# Arabic labels for the app's Arabic mode (names stay in English for now)
AR = {
    "Type 2 diabetes": "السكري من النوع الثاني",
    "Hypertension": "ارتفاع ضغط الدم",
    "Asthma": "الربو",
    "Iron-deficiency anemia": "فقر الدم بنقص الحديد",
    "High cholesterol": "ارتفاع الكوليسترول",
    "Common cold": "نزلة برد",
    "Penicillin": "البنسلين",
    "Peanuts": "الفول السوداني",
    "Sulfa drugs": "أدوية السلفا",
    "Metformin 500 mg": "ميتفورمين 500 ملغ",
    "Amlodipine 5 mg": "أملوديبين 5 ملغ",
    "Salbutamol inhaler": "بخاخ سالبوتامول",
    "Ferrous sulfate 200 mg": "كبريتات الحديدوز 200 ملغ",
    "Atorvastatin 20 mg": "أتورفاستاتين 20 ملغ",
    "Paracetamol 500 mg": "باراسيتامول 500 ملغ",
}


def both(text):
    """Return {en, ar}. If there is no Arabic label yet, reuse the English text."""
    return {"en": text, "ar": AR.get(text, text)}


def age_from(dob_text):
    born = date.fromisoformat(dob_text)
    today = date.today()
    return today.year - born.year - ((today.month, today.day) < (born.month, born.day))


def main():
    conn = sqlite3.connect(DB_FILE)
    patients = []
    for pid, name, dob, blood, allergy in conn.execute(
        "SELECT patient_id, full_name, date_of_birth, blood_group, allergy "
        "FROM patients ORDER BY patient_id"
    ).fetchall():
        visits = conn.execute(
            "SELECT v.visit_date, d.diagnosis_name, v.medication "
            "FROM visits v JOIN diagnoses d ON d.diagnosis_code = v.diagnosis_code "
            "WHERE v.patient_id = ? ORDER BY v.visit_date DESC", (pid,)
        ).fetchall()
        if not visits:
            continue

        first_year = {}
        meds = []
        for visit_date, diagnosis, medication in visits:
            year = int(visit_date[:4])
            first_year[diagnosis] = min(year, first_year.get(diagnosis, year))
            if medication and medication not in meds:
                meds.append(medication)

        item = {
            "id": pid,
            "name": {"en": name, "ar": name},
            "age": age_from(dob),
            "blood": blood,
            "cond": [dict(both(dx), s=yr) for dx, yr in sorted(first_year.items())],
            "allergy": [] if allergy == "None" else [both(allergy)],
            "meds": [both(m) for m in meds],
            "visits": [dict(both(dx), d=vd) for vd, dx, _ in visits[:3]],
        }
        patients.append(item)
    conn.close()

    with open(OUT_FILE, "w", encoding="utf-8") as f:
        f.write("// Generated by export_for_app.py. Synthetic data only.\n")
        f.write("window.PATIENTS = " + json.dumps(patients, ensure_ascii=False, indent=1) + ";\n")
    print(f"Done. Exported {len(patients)} patients to {OUT_FILE}")


if __name__ == "__main__":
    main()
